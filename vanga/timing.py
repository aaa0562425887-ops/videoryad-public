#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Тайминг сцен фильма «Ванга 2027» → timing.json.

Сцена = (id, секунда озвучки ПЛАНЕТА, с которой она начинается, вставка в секундах,
конец голоса сцены или None). Паузы [ПАУЗА N с] и врезки — вставки В НАЧАЛО сцены
(диктор молчит, картинка идёт). Границы — по тишинам golos.mp3 (silencedetect −38 дБ, 0,3 с),
срез за 0,15 с до следующего слова. Голос блока 0 — golos/planeta0/planeta0.mp3 (80,48 с).

    python3 timing.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# блок 0 «ХУК» (первая минута — на утверждение отдельным файлом)
SCENES = [
    ("01", 0.000, 1.0, None),     # [ТИШИНА 1 с] цифры 2027 · «Две тысячи двадцать седьмой год.»
    ("02", 2.220, 1.0, None),     # [ПАУЗА 1 с] заголовки · «Осенью две тысячи двадцать шестого… не будет править Россией.»
    ("03", 13.580, 1.5, None),    # [ПАУЗА 1,5 с] строка подчёркнута · «Строку приписывают женщине… болгарского города.»
    ("04", 20.850, 4.0, None),    # [ВАНГА без слов 4 с] · «Ей же приписывают другое. „Всё растает…“»
    ("05", 29.440, 1.0, None),    # [ПАУЗА 1 с] · «И третье… „До самой смерти“.»
    ("06", 36.790, 1.0, None),    # [ПАУЗА 1 с] · «И четвёртое. Самое тёмное. „Новый человек грядёт…“»
    ("07", 42.300, 1.5, None),    # [ПАУЗА 1,5 с, цифра 8] · «А про сам двадцать седьмой год… которые от неё ушли.»
    ("08", 50.230, 1.0, None),    # [ПАУЗА 1 с] · «Почему её слушают до сих пор?… Запись сохранилась.»
    ("09", 63.760, 11.0, 63.760), # [ВАНГА Горещо 2 11:43–11:52, оригинал 2 с, Ольга] + [ПАУЗА 1,5 с] — голоса ПЛАНЕТЫ нет
    ("10", 63.760, 0.0, None),    # «Сегодня соберём всё… Что она сказала на самом деле?»
    ("11", 80.480, 7.0, 80.480),  # [ПАУЗА 2 с + ТИТР 5 с] — голоса нет
]
TAIL = 0.0
# вырезанные отрезки голоса (оговорки) — секунды озвучки
CUTS = []
# паузы внутри сцены: id → [(секунда озвучки, длина)]
MID = {}


def main():
    total = 80.48
    out = []
    film = 0.0
    for i, (sid, v0, ins, vend) in enumerate(SCENES):
        v1 = vend if vend is not None else (SCENES[i + 1][1] if i + 1 < len(SCENES) else total)
        mid = MID.get(sid, [])
        dur = ins + (v1 - v0) + sum(m for _, m in mid)
        out.append({"id": sid, "voice_start": v0, "voice_end": v1, "insert": ins, "mid": mid, "dur": round(dur, 3),
                    "film_start": round(film, 3), "film_end": round(film + dur, 3)})
        film += dur
    json.dump({"voice_end": total, "cuts": CUTS, "scenes": out}, open(os.path.join(HERE, "timing.json"), "w"),
              ensure_ascii=False, indent=1)
    for s in out:
        print("%-4s voice %7.2f-%7.2f  ins %4.1f  dur %6.2f  film %7.2f" % (s["id"], s["voice_start"], s["voice_end"], s["insert"], s["dur"], s["film_start"]))
    print("итого %.2f с" % film)


if __name__ == "__main__":
    main()
