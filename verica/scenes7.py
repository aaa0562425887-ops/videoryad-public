def frag_scene(f):
    def fn(t, dur):
        img = verica("r_" + f["id"], f["file"], t + f["start"], zoom=1.8, cx=0.48, cy=0.30, push=0.03, hand=2.0, k_grade=0.85)
        env_v = envelope(f["file"], f["start"], dur)
        env_o = envelope(f["olga"], 0.0, f["olga_dur"])
        lay = oscillo([(env_v, 0.0, C.WHITE), (env_o, 2.3, C.RED)], t, H - 150, 54, SAFE_X, W - SAFE_X)
        k_orig = C.seg(t, 0.2, 0.6) * (1 - C.seg(t, 2.0, 2.4))
        k_per = C.seg(t, 2.3, 2.7)
        lays = [lay, label("ОРИГИНАЛЬНЫЙ ЗВУК", k_orig, 120, 34, C.GREY, x=W - SAFE_X, anchor="rs"),
                label("ПЕРЕВОД ЗА КАДРОМ", k_per, 120, 34, C.RED, x=W - SAFE_X, anchor="rs"),
                label(f["tema"], C.seg(t, 0.1, 0.5), 120, 40, C.WHITE, x=SAFE_X, anchor="ls", track=0.16)]
        n = len(f["lines"])
        for i, (txt, t0, t1) in enumerate(f["lines"]):
            k = C.seg(t, t0, t1)
            if k <= 0 or (i + 3 < n and t >= f["lines"][i + 3][1]):
                continue
            y = 196 + (i % 3) * 54
            last = (i == n - 1) or t < f["lines"][i + 1][1]
            lays.append(fx.typed(txt, k, "head_r", 40, C.WHITE, SAFE_X, y, 0.02, last, t))
        lays.append(C.caption(*CAP_R, k=C.seg(t, 0.4, 0.9)))
        img = C.over(img, *lays).convert("RGB")
        return C.finish(flash(img, t, 0.08, 0.35), t, dur, fi=0.0, fo=0.3, grain_k=0.03, vig=0.3)
    return fn


